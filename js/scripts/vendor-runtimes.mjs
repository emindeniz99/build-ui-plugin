// Bundles each runtime in js/runtimes into src/main/webapp/runtimes/<id>.js,
// the files the plugin ships. `--check` rebuilds in memory and fails when a
// shipped file is missing or out of date, so CI catches a forgotten rebuild.
// Both modes fail when a bundle, host.js or the sandbox boot script grows past its size budget.
import { build } from 'esbuild';
import { readFileSync, existsSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { gzipSync } from 'node:zlib';

const js = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.resolve(js, '../src/main/webapp/runtimes');
const check = process.argv.includes('--check');
const version = (pkg) => JSON.parse(readFileSync(path.join(js, 'node_modules', pkg, 'package.json'), 'utf8')).version;
// The packages each runtime bundles, named in its banner. All are MIT licensed.
const PACKAGES = {
  'preact11-htm3': ['preact', 'htm'],
  'schema-form': ['preact', 'htm'],
  'alpine3-csp': ['@alpinejs/csp'],
  alpine3: ['alpinejs'],
  vue3: ['vue'],
};
function banner(id) {
  if (!PACKAGES[id]) throw new Error(`no package list for ${id}; add one to PACKAGES`);
  const list = PACKAGES[id].map((pkg) => `${pkg} ${version(pkg)}`).join(', ');
  return `/*! build-ui runtime. Generated by js/scripts/vendor-runtimes.mjs; do not edit. ${list} (MIT) */`;
}

// Size budgets, gzip bytes. Growing past one is a decision: raise it in the same commit.
const BUDGETS = {
  'preact11-htm3': 8 * 1024, 'schema-form': 9 * 1024, host: 4 * 1024, 'sandbox-boot': 2 * 1024,
  'alpine3-csp': 25 * 1024, alpine3: 21 * 1024, vue3: 68 * 1024,
};
const gzipSize = (text) => gzipSync(text, { level: 9 }).length;
function budget(id, text) {
  const size = gzipSize(text);
  const limit = BUDGETS[id];
  if (limit === undefined) throw new Error(`no size budget for ${id}; add one to BUDGETS`);
  console.log(`${id}: ${(size / 1024).toFixed(1)} KB gzip (budget ${(limit / 1024).toFixed(0)} KB)`);
  return size <= limit;
}

let stale = 0;
if (!budget('host', readFileSync(path.resolve(js, '../src/main/webapp/host.js'), 'utf8'))) stale++;
if (!budget('sandbox-boot', readFileSync(path.resolve(js, '../src/main/webapp/sandbox/boot.js'), 'utf8'))) stale++;
for (const file of readdirSync(path.join(js, 'runtimes')).filter((f) => f.endsWith('.mjs'))) {
  const id = file.slice(0, -'.mjs'.length);
  const target = path.join(out, `${id}.js`);
  const result = await build({
    entryPoints: [path.join(js, 'runtimes', file)],
    bundle: true,
    format: 'esm',
    minify: true,
    legalComments: 'none',
    banner: { js: banner(id) },
    target: 'es2022',
    outfile: target,
    write: false,
  });
  const fresh = result.outputFiles[0].text;
  if (!budget(id, fresh)) stale++;
  if (check) {
    const shipped = existsSync(target) ? readFileSync(target, 'utf8') : null;
    if (fresh !== shipped) {
      console.error(`${path.relative(js, target)} is out of date; run: pnpm --dir projects/jenkins-ui/js vendor`);
      stale++;
    }
  } else {
    writeFileSync(target, fresh);
    console.log(`wrote ${path.relative(js, target)}`);
  }
}
process.exit(stale ? 1 : 0);
