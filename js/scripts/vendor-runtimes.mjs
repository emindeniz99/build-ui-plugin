// Bundles each runtime in js/runtimes into src/main/webapp/runtimes/<id>.js,
// the files the plugin ships. `--check` rebuilds in memory and fails when a
// shipped file is missing or out of date, so CI catches a forgotten rebuild.
import { build } from 'esbuild';
import { readFileSync, existsSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const js = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.resolve(js, '../src/main/webapp/runtimes');
const check = process.argv.includes('--check');
const version = (pkg) => JSON.parse(readFileSync(path.join(js, 'node_modules', pkg, 'package.json'), 'utf8')).version;
const banner = `/*! build-ui runtime. Generated by js/scripts/vendor-runtimes.mjs; do not edit. preact ${version('preact')}, htm ${version('htm')} (MIT) */`;

let stale = 0;
for (const file of readdirSync(path.join(js, 'runtimes')).filter((f) => f.endsWith('.mjs'))) {
  const id = file.slice(0, -'.mjs'.length);
  const target = path.join(out, `${id}.js`);
  const result = await build({
    entryPoints: [path.join(js, 'runtimes', file)],
    bundle: true,
    format: 'esm',
    minify: true,
    legalComments: 'none',
    banner: { js: banner },
    target: 'es2022',
    outfile: target,
    write: !check,
  });
  if (check) {
    const fresh = result.outputFiles[0].text;
    const shipped = existsSync(target) ? readFileSync(target, 'utf8') : null;
    if (fresh !== shipped) {
      console.error(`${path.relative(js, target)} is out of date; run: pnpm --dir projects/jenkins-ui/js vendor`);
      stale++;
    }
  } else {
    console.log(`wrote ${path.relative(js, target)}`);
  }
}
process.exit(stale ? 1 : 0);
